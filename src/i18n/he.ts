/** Relative time in Hebrew for "last seen" and "next review". */
export function relTime(ts: number, now = Date.now()): string {
  const diff = ts - now;
  const abs = Math.abs(diff);
  const min = 60_000;
  const hour = 60 * min;
  const day = 24 * hour;
  const future = diff > 0;
  const fmt = (s: string) => (future ? `בעוד ${s}` : `לפני ${s}`);
  if (abs < min) return future ? 'עכשיו' : 'ממש עכשיו';
  if (abs < hour) {
    const m = Math.round(abs / min);
    return fmt(m === 1 ? 'דקה' : `${m} דקות`);
  }
  if (abs < day) {
    const h = Math.round(abs / hour);
    return fmt(h === 1 ? 'שעה' : h === 2 ? 'שעתיים' : `${h} שעות`);
  }
  const d = Math.round(abs / day);
  if (d === 1) return future ? 'מחר' : 'אתמול';
  if (d < 30) return fmt(d === 2 ? 'יומיים' : `${d} ימים`);
  const mo = Math.round(d / 30);
  if (mo < 12) return fmt(mo === 1 ? 'חודש' : mo === 2 ? 'חודשיים' : `${mo} חודשים`);
  const y = Math.round(d / 365);
  return fmt(y === 1 ? 'שנה' : y === 2 ? 'שנתיים' : `${y} שנים`);
}

export function levelTitle(level: number): string {
  const titles = t.levels;
  return titles[Math.min(titles.length - 1, Math.floor((level - 1) / 3))]!;
}
